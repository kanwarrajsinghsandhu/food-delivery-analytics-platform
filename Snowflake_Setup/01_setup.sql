-- Zomato project setup: warehouse, database, schemas, and dbt role
-- Co-authored with CoCo
USE ROLE ACCOUNTADMIN;

-- Compute: extra small, auto-suspend fast so that the trial credits last
CREATE WAREHOUSE IF NOT EXISTS ZOMATO_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND   =  60
    AUTO_RESUME    = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- Database + Medallion Schema 
CREATE DATABASE IF NOT EXISTS ZOMATO;
CREATE SCHEMA IF NOT EXISTS ZOMATO.BRONZE;  -- Iceberg Tables Spark Wrote
CREATE SCHEMA IF NOT EXISTS ZOMATO.RAW;     -- only used by the COPY fallback path
CREATE SCHEMA IF NOT EXISTS ZOMATO.STAGING; -- clean/conformed (dbt)
CREATE SCHEMA IF NOT EXISTS ZOMATO.MARTS;   -- Gold, Iceberg (dbt)
CREATE SCHEMA IF NOT EXISTS ZOMATO.SNAPSHOTS; -- SCD2 history (dbt)
CREATE SCHEMA IF NOT EXISTS ZOMATO.AI;        -- LLM enriched tables (OpenAI Jobs)

-- A role dbt/Airflow will use
CREATE ROLE IF NOT EXISTS DBT_ROLE;
GRANT USAGE ON WAREHOUSE ZOMATO_WH TO DBT_ROLE;
GRANT OPERATE ON WAREHOUSE ZOMATO_WH TO DBT_ROLE;
GRANT ALL ON DATABASE ZOMATO TO DBT_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE ZOMATO TO DBT_ROLE;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE ZOMATO TO DBT_ROLE;
GRANT ALL ON FUTURE TABLES IN DATABASE ZOMATO TO DBT_ROLE;
GRANT ALL ON FUTURE VIEWS IN DATABASE ZOMATO TO DBT_ROLE;

-- Let your login use the role (replace with your Snowflake username).
SET my_user = CURRENT_USER();
GRANT ROLE DBT_ROLE TO USER IDENTIFIER($my_user);

SELECT 'setup complete' AS status;



